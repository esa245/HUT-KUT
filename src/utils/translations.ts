export const formatNumber = (num: number, lang: Language = 'bn'): string => {
  if (num >= 1000000000) {
    const val = (num / 1000000000).toFixed(2);
    return `${val}B`;
  }
  if (num >= 1000000) {
    const val = (num / 1000000).toFixed(2);
    return `${val}M`;
  }
  if (num >= 10000) {
    const val = (num / 1000).toFixed(1);
    return `${val}K`;
  }
  return num.toLocaleString();
};

export const toBengaliDigits = (numStr: string | number): string => {
  const bnDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
  return String(numStr).replace(/[0-9]/g, (w) => bnDigits[+w]);
};
